package com.possaas.possaasbackend.productvariant;

import com.possaas.possaasbackend.product.Product;
import com.possaas.possaasbackend.product.ProductRepository;
import com.possaas.possaasbackend.productvariant.dto.AssignProductAttributeRequest;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.InjectMocks;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;

import java.util.List;
import java.util.Optional;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.*;

@ExtendWith(MockitoExtension.class)
class ProductAttributeServiceTest {

    @Mock
    private ProductRepository productRepository;

    @Mock
    private BusinessAttributeRepository businessAttributeRepository;

    @Mock
    private ProductAttributeRepository productAttributeRepository;

    @InjectMocks
    private ProductAttributeService productAttributeService;

    private UUID businessId;
    private UUID productId;
    private UUID attributeId;
    private UUID productAttributeId;

    private Product product;
    private BusinessAttribute businessAttribute;
    private ProductAttribute productAttribute;

    @BeforeEach
    void setUp() {
        businessId = UUID.randomUUID();
        productId = UUID.randomUUID();
        attributeId = UUID.randomUUID();
        productAttributeId = UUID.randomUUID();

        // Product is mocked because its ID is generated by JPA
        product = mock(Product.class);

        businessAttribute = new BusinessAttribute();
        businessAttribute.setId(attributeId);
        businessAttribute.setBusinessId(businessId);

        productAttribute = new ProductAttribute();
        productAttribute.setId(productAttributeId);
        productAttribute.setBusinessId(businessId);
        productAttribute.setProductId(productId);
        productAttribute.setAttributeId(attributeId);
    }

    // =========================================================
    // ASSIGN ATTRIBUTE
    // =========================================================

    @Test
    void shouldAssignAttributeToProductSuccessfully() {
        AssignProductAttributeRequest request =
                new AssignProductAttributeRequest(attributeId);

        when(productRepository.findByIdAndBusiness_Id(productId, businessId))
                .thenReturn(Optional.of(product));

        when(product.getId()).thenReturn(productId);

        when(businessAttributeRepository.findByIdAndBusinessId(attributeId, businessId))
                .thenReturn(Optional.of(businessAttribute));

        when(productAttributeRepository
                .existsByBusinessIdAndProductIdAndAttributeId(
                        businessId, productId, attributeId))
                .thenReturn(false);

        when(productAttributeRepository.save(any(ProductAttribute.class)))
                .thenReturn(productAttribute);

        ProductAttribute result =
                productAttributeService.assignAttribute(
                        businessId, productId, request);

        assertNotNull(result);
        assertEquals(productAttributeId, result.getId());
        assertEquals(businessId, result.getBusinessId());
        assertEquals(productId, result.getProductId());
        assertEquals(attributeId, result.getAttributeId());

        verify(productAttributeRepository).save(any(ProductAttribute.class));
    }

    @Test
    void shouldRejectAssignmentWhenProductDoesNotExist() {
        AssignProductAttributeRequest request =
                new AssignProductAttributeRequest(attributeId);

        when(productRepository.findByIdAndBusiness_Id(productId, businessId))
                .thenReturn(Optional.empty());

        assertThrows(IllegalArgumentException.class,
                () -> productAttributeService.assignAttribute(
                        businessId, productId, request));

        verify(businessAttributeRepository, never())
                .findByIdAndBusinessId(any(), any());

        verify(productAttributeRepository, never())
                .save(any(ProductAttribute.class));
    }

    @Test
    void shouldRejectAssignmentWhenAttributeDoesNotBelongToBusiness() {
        AssignProductAttributeRequest request =
                new AssignProductAttributeRequest(attributeId);

        when(productRepository.findByIdAndBusiness_Id(productId, businessId))
                .thenReturn(Optional.of(product));

        when(businessAttributeRepository.findByIdAndBusinessId(attributeId, businessId))
                .thenReturn(Optional.empty());

        assertThrows(IllegalArgumentException.class,
                () -> productAttributeService.assignAttribute(
                        businessId, productId, request));

        verify(productAttributeRepository, never())
                .save(any(ProductAttribute.class));
    }

    @Test
    void shouldRejectDuplicateAttributeAssignment() {
        AssignProductAttributeRequest request =
                new AssignProductAttributeRequest(attributeId);

        when(productRepository.findByIdAndBusiness_Id(productId, businessId))
                .thenReturn(Optional.of(product));

        when(product.getId()).thenReturn(productId);

        when(businessAttributeRepository.findByIdAndBusinessId(attributeId, businessId))
                .thenReturn(Optional.of(businessAttribute));

        when(productAttributeRepository
                .existsByBusinessIdAndProductIdAndAttributeId(
                        businessId, productId, attributeId))
                .thenReturn(true);

        assertThrows(IllegalArgumentException.class,
                () -> productAttributeService.assignAttribute(
                        businessId, productId, request));

        verify(productAttributeRepository, never())
                .save(any(ProductAttribute.class));
    }

    // =========================================================
    // GET PRODUCT ATTRIBUTES
    // =========================================================

    @Test
    void shouldReturnAllProductAttributes() {
        when(productRepository.findByIdAndBusiness_Id(productId, businessId))
                .thenReturn(Optional.of(product));

        when(productAttributeRepository.findAllByBusinessIdAndProductId(
                businessId, productId))
                .thenReturn(List.of(productAttribute));

        List<ProductAttribute> result =
                productAttributeService.getProductAttributes(
                        businessId, productId);

        assertEquals(1, result.size());
        assertEquals(productAttributeId, result.get(0).getId());
    }

    @Test
    void shouldReturnEmptyListWhenProductHasNoAttributes() {
        when(productRepository.findByIdAndBusiness_Id(productId, businessId))
                .thenReturn(Optional.of(product));

        when(productAttributeRepository.findAllByBusinessIdAndProductId(
                businessId, productId))
                .thenReturn(List.of());

        List<ProductAttribute> result =
                productAttributeService.getProductAttributes(
                        businessId, productId);

        assertTrue(result.isEmpty());
    }

    @Test
    void shouldRejectGettingAttributesForNonexistentProduct() {
        when(productRepository.findByIdAndBusiness_Id(productId, businessId))
                .thenReturn(Optional.empty());

        assertThrows(IllegalArgumentException.class,
                () -> productAttributeService.getProductAttributes(
                        businessId, productId));

        verify(productAttributeRepository, never())
                .findAllByBusinessIdAndProductId(any(), any());
    }

    // =========================================================
    // GET PRODUCT ATTRIBUTE BY ID
    // =========================================================

    @Test
    void shouldReturnProductAttributeById() {
        when(productRepository.findByIdAndBusiness_Id(productId, businessId))
                .thenReturn(Optional.of(product));

        when(productAttributeRepository.findByIdAndBusinessIdAndProductId(
                productAttributeId, businessId, productId))
                .thenReturn(Optional.of(productAttribute));

        ProductAttribute result =
                productAttributeService.getProductAttributeById(
                        businessId, productId, productAttributeId);

        assertNotNull(result);
        assertEquals(productAttributeId, result.getId());
    }

    @Test
    void shouldThrowExceptionWhenProductAttributeAssignmentDoesNotExist() {
        when(productRepository.findByIdAndBusiness_Id(productId, businessId))
                .thenReturn(Optional.of(product));

        when(productAttributeRepository.findByIdAndBusinessIdAndProductId(
                productAttributeId, businessId, productId))
                .thenReturn(Optional.empty());

        assertThrows(IllegalArgumentException.class,
                () -> productAttributeService.getProductAttributeById(
                        businessId, productId, productAttributeId));
    }

    @Test
    void shouldRejectGettingAttributeWhenProductDoesNotExist() {
        when(productRepository.findByIdAndBusiness_Id(productId, businessId))
                .thenReturn(Optional.empty());

        assertThrows(IllegalArgumentException.class,
                () -> productAttributeService.getProductAttributeById(
                        businessId, productId, productAttributeId));

        verify(productAttributeRepository, never())
                .findByIdAndBusinessIdAndProductId(any(), any(), any());
    }

    // =========================================================
    // REMOVE PRODUCT ATTRIBUTE
    // =========================================================

    @Test
    void shouldRemoveAttributeFromProductSuccessfully() {
        when(productRepository.findByIdAndBusiness_Id(productId, businessId))
                .thenReturn(Optional.of(product));

        when(productAttributeRepository.findByIdAndBusinessIdAndProductId(
                productAttributeId, businessId, productId))
                .thenReturn(Optional.of(productAttribute));

        productAttributeService.removeAttribute(
                businessId, productId, productAttributeId);

        verify(productAttributeRepository).delete(productAttribute);
    }

    @Test
    void shouldThrowExceptionWhenRemovingNonexistentAttributeAssignment() {
        when(productRepository.findByIdAndBusiness_Id(productId, businessId))
                .thenReturn(Optional.of(product));

        when(productAttributeRepository.findByIdAndBusinessIdAndProductId(
                productAttributeId, businessId, productId))
                .thenReturn(Optional.empty());

        assertThrows(IllegalArgumentException.class,
                () -> productAttributeService.removeAttribute(
                        businessId, productId, productAttributeId));

        verify(productAttributeRepository, never())
                .delete(any(ProductAttribute.class));
    }
}
